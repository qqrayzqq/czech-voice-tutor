let language = 'ru';
const listeners = new Set();
const staticBindings = [];
export function getLanguage() { return language; }
export function t(source, values = {}) {
  const translated = language === 'uk' ? ukrainian[source] || source : source;
  return translated.replace(/\{(\w+)\}/g, (match, key) => values[key] ?? match);
}
export function onLanguageChange(listener) { listeners.add(listener); return () => listeners.delete(listener); }
export function setLanguage(value) {
  language = value === 'uk' ? 'uk' : 'ru';
  if (typeof document !== 'undefined') document.documentElement.lang = language;
  for (const binding of staticBindings) binding();
  for (const listener of listeners) listener();
}
// Capture only the original UI nodes. Saved replies/explanations are never translated.
export function registerStaticStrings(root = document) {
  const walker = document.createTreeWalker(root, 4);
  let node;
  while ((node = walker.nextNode())) {
    const source = node.textContent.trim();
    if (!Object.hasOwn(ukrainian, source)) continue;
    const target = node;
    const original = node.textContent;
    staticBindings.push(() => { target.textContent = original.replace(source, t(source)); });
  }
  root.querySelectorAll('[aria-label], [title], [placeholder]').forEach(element => {
    for (const attribute of ['aria-label', 'title', 'placeholder']) {
      const source = element.getAttribute(attribute);
      if (Object.hasOwn(ukrainian, source)) staticBindings.push(() => element.setAttribute(attribute, t(source)));
    }
  });
}
export function initializeLocalization(search = window.location.search) {
  registerStaticStrings();
  const params = new URLSearchParams(search);
  // A button's locale is only a loading/error hint. Authenticated API data wins.
  setLanguage(params.get('lang'));
}
